#!/usr/bin/env python3
"""Generate or verify tool-contract.json from the server's actually registered tools."""
import argparse
import asyncio
import hashlib
import json
import re
import sys
try:
    import tomllib
except ModuleNotFoundError:
    tomllib = None
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CONTRACT_PATH = ROOT / "tool-contract.json"
PLUGIN_MANIFESTS = (
    ".claude-plugin/plugin.json",
    ".codex-plugin/plugin.json",
    ".cursor-plugin/plugin.json",
)


def canonical(obj):
    return json.dumps(
        obj, sort_keys=True, ensure_ascii=False, separators=(",", ":")
    ).encode("utf-8")


def sha(obj):
    return hashlib.sha256(canonical(obj)).hexdigest()


def read_project_version():
    if tomllib is not None:
        with open(ROOT / "pyproject.toml", "rb") as f:
            return tomllib.load(f)["project"]["version"]
    text = (ROOT / "pyproject.toml").read_text(encoding="utf-8")
    project = re.search(r"(?ms)^\[project\]\s*$(.*?)(?=^\[|\Z)", text)
    version = re.search(r'^\s*version\s*=\s*["\']([^"\']+)["\']', project.group(1)) if project else None
    if version is None:
        raise ValueError("Could not find version in [project] table of pyproject.toml")
    return version.group(1)


def _load_server():
    if str(ROOT) not in sys.path:
        sys.path.insert(0, str(ROOT))
    from seo_pulse_mcp import server

    try:
        import mcp.server.fastmcp  # noqa: F401
    except ImportError:
        raise SystemExit("找不到官方 mcp SDK，無法產生合約 / the real `mcp` SDK is required")
    if not hasattr(server.mcp, "list_tools"):
        raise SystemExit("伺服器使用的是替代 stub，無法產生合約 / server fell back to the stub FastMCP")
    return server


def build_contract():
    server = _load_server()
    tools = asyncio.run(server.mcp.list_tools())
    entries = []
    for tool in sorted(tools, key=lambda t: t.name):
        description = tool.description or ""
        schema = tool.inputSchema
        entries.append(
            {
                "name": tool.name,
                "description": description,
                "input_schema": schema,
                "sha256": {
                    "description": sha(description),
                    "input_schema": sha(schema),
                    "tool": sha(
                        {"name": tool.name, "description": description, "input_schema": schema}
                    ),
                },
            }
        )
    version = read_project_version()
    return {
        "$comment": "Generated by scripts/generate_tool_contract.py — do not edit by hand.",
        "contract_format": 1,
        "version": version,
        "server": "seo-pulse",
        "hash_algorithm": "sha256",
        "canonical_json": "json.dumps(sort_keys=True, ensure_ascii=False, separators=(',', ':')), UTF-8",
        "fingerprint": sha([e["sha256"]["tool"] for e in entries]),
        "tools": entries,
    }


def diff_contracts(expected, actual):
    """Return human-readable lines describing how `actual` differs from `expected`."""
    lines = []
    if expected.get("version") != actual.get("version"):
        lines.append(
            f"版本不同 / version differs: {expected.get('version')} -> {actual.get('version')}"
        )
    exp = {t["name"]: t for t in expected.get("tools", [])}
    act = {t["name"]: t for t in actual.get("tools", [])}
    for name in sorted(exp.keys() - act.keys()):
        lines.append(f"工具被移除 / tool removed: {name}")
    for name in sorted(act.keys() - exp.keys()):
        lines.append(f"工具新增 / tool added: {name}")
    for name in sorted(exp.keys() & act.keys()):
        for field in ("description", "input_schema"):
            if exp[name].get(field) != act[name].get(field):
                lines.append(f"工具 {name} 的 {field} 不同 / tool {name}: {field} differs")
        if exp[name].get("sha256") != act[name].get("sha256"):
            lines.append(f"工具 {name} 的 sha256 不同 / tool {name}: sha256 differs")
    if expected.get("fingerprint") != actual.get("fingerprint"):
        lines.append(
            f"指紋不同 / fingerprint differs: {expected.get('fingerprint')} -> {actual.get('fingerprint')}"
        )
    return lines


def _load_existing():
    if CONTRACT_PATH.exists():
        return json.loads(CONTRACT_PATH.read_text(encoding="utf-8"))
    return None


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="只比對，不寫檔 / compare without writing")
    args = parser.parse_args(argv)

    actual = build_contract()
    existing = _load_existing()

    if args.check:
        if existing is None:
            print("tool-contract.json 不存在 / tool-contract.json is missing")
            return 1
        lines = diff_contracts(existing, actual)
        if lines:
            print("\n".join(lines))
            return 1
        print("OK: 本機伺服器與 tool-contract.json 一致 / server matches tool-contract.json")
        return 0

    if (
        existing is not None
        and existing.get("version") == actual["version"]
        and existing.get("fingerprint") != actual["fingerprint"]
    ):
        print("\n".join(diff_contracts(existing, actual)))
        print(
            "工具內容已改變但版本號未變，請先更新 pyproject.toml 與三個 plugin.json "
            f"({', '.join(PLUGIN_MANIFESTS)}) 的 version 再重新產生。\n"
            "Tools changed but the version did not: bump the version in pyproject.toml "
            "and all three plugin.json files first, then re-run."
        )
        return 1

    CONTRACT_PATH.write_text(
        json.dumps(actual, indent=2, ensure_ascii=False) + "\n", encoding="utf-8"
    )
    print(f"已寫入 / wrote {CONTRACT_PATH.name} (fingerprint {actual['fingerprint']})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
